// Builds the redirect map from the live URL inventory + the BetterLinks export.
//
// Every URL WordPress serves today must either exist at the same path after
// the migration or 301 somewhere real — that is §C ground rule 5, and this is
// what enforces it. The output is `src/lib/redirects.ts`, which astro.config
// reads; nothing is hand-written twice.
//
// Run after `node scripts/wp-inventory.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';

const inv = JSON.parse(readFileSync('reference/wp-inventory.json', 'utf8'));
const links = JSON.parse(readFileSync('reference/betterlinks-map.json', 'utf8'));
const p = (u) => new URL(u).pathname;

/** Paths this build serves itself. Anything here must NOT be redirected. */
const BUILT = new Set(['/', '/features/', '/docs/', '/changelog/', '/privacy-policy/',
  '/feature-request/', '/blog/']);

const rules = [];
const add = (from, to, status, why) => rules.push({ from, to, status, why });

/* Posts move to /blog/<slug>/ — the A1 decision, taken against the guide's own
 * A4 recommendation and recorded with its cost. The guide's redirect table has
 * this the other way round; it predates the decision. */
for (const post of inv.posts) add(p(post.link), `/blog/${post.slug}/`, 301, 'post moved under /blog/');

/* Pages, docs, doc categories and categories all keep their paths. They are
 * listed so that a page appearing in WordPress that this build does NOT serve
 * shows up as an error rather than a launch-day 404 — which is exactly how
 * /feature-request/ was found. */
const unbuilt = [];
for (const page of inv.pages) if (!BUILT.has(p(page.link))) unbuilt.push(p(page.link));

/* An empty category is a thin page; send it to the blog index rather than
 * building one that lists nothing. */
for (const cat of inv.categories) {
  if (cat.count === 0) add(p(cat.link), '/blog/', 301, 'category has no posts');
}

/* BetterLinks — cloaked campaign links currently served by WordPress. They
 * carry real traffic (the export records hits) and would 404 the moment WP
 * stops serving the front end. Statuses are the ones BetterLinks itself uses. */
for (const l of links) add(l.from, l.to, l.status === 301 ? 301 : 302, 'BetterLinks');

/* WordPress' own surfaces are wildcard rules, 410s and one rewrite. Astro's
 * `redirects` cannot express any of those — it requires a dynamic destination
 * to be an existing route with the same parameters, and has no notion of a
 * status outside 3xx. They go into the platform routing table instead, which
 * astro.config merges into the built Vercel config. */
const platform = [
  { src: '^/index\\.php(/.*)?$', dest: '$1', status: 301,
    why: 'legacy index.php permalinks' },
  { src: '^/tag/.*', dest: '/blog/', status: 301,
    why: 'tag archives were never a destination' },
  { src: '^/author/.*', dest: '/blog/', status: 301,
    why: 'A1 decision: single author, consolidate' },
  { src: '^/(wp-json|wp-admin|wp-includes)(/.*)?$', status: 410,
    why: 'gone, and saying so stops crawlers retrying' },
  { src: '^/xmlrpc\\.php$', status: 410, why: 'gone' },
];

const conflicts = rules.filter((r) => BUILT.has(r.from));
const seen = new Map();
const dupes = [];
for (const r of rules) {
  if (seen.has(r.from)) dupes.push(r.from);
  seen.set(r.from, r);
}

const body = rules
  .filter((r) => r.status !== 200)
  .map((r) => `  /* ${r.why} */\n  { from: ${JSON.stringify(r.from)}, to: ${JSON.stringify(r.to)}, status: ${r.status} },`)
  .join('\n');

/* Every rule goes into the platform table, including the one-to-one ones.
 *
 * Astro's own `redirects` cannot be used for these: with trailingSlash 'always'
 * the Vercel adapter emits `^/some-post$` — no trailing slash — and puts the
 * 308 slash-normaliser AHEAD of it. Every real old WordPress URL ends in a
 * slash, so the redirect never matches it, and the slash-less form gets 308'd
 * to a slashed URL that then matches nothing. Both forms 404. These patterns
 * accept the slash either way and are placed BEFORE the normaliser. */
const oneToOne = rules
  .filter((r) => r.status !== 200)
  .map((r) => ({
    src: '^' + r.from.replace(/\/$/, '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '/?$',
    dest: r.to,
    status: r.status,
    why: r.why,
  }));

const platformBody = [...oneToOne, ...platform]
  .map((r) => `  /* ${r.why} */\n  { src: ${JSON.stringify(r.src)}, ${r.dest ? `dest: ${JSON.stringify(r.dest)}, ` : ''}status: ${r.status} },`)
  .join('\n');

writeFileSync('src/lib/redirects.ts', `/**
 * Generated by scripts/gen-redirects.mjs — do not edit by hand.
 *
 * Every URL WordPress serves today either exists at the same path in this build
 * or appears here. Regenerate after running scripts/wp-inventory.mjs.
 *
 * ${rules.filter((r) => r.status !== 200).length} one-to-one rules plus ${platform.length} platform rules.
 * \`redirects\` below is the readable record; \`platformRoutes\` is what actually
 * ships — see the note above it.
 */
export interface Redirect {
  from: string;
  to: string;
  status: 301 | 302;
}

export const redirects: Redirect[] = [
${body}
];

/**
 * What actually ships. Merged into .vercel/output/config.json by the
 * integration in astro.config, PREPENDED so these run before the trailing-slash
 * normaliser.
 *
 * Astro's own \`redirects\` is deliberately not used: with trailingSlash
 * 'always' its adapter emits slash-less patterns and orders them after the 308
 * normaliser, so a real old URL — which always ends in a slash — matches
 * nothing and 404s. Every pattern here accepts the slash either way.
 */
export interface PlatformRoute {
  src: string;
  dest?: string;
  status: number;
}

export const platformRoutes: PlatformRoute[] = [
${platformBody}
];
`);

console.log(`${rules.filter((r) => r.status !== 200).length} redirects + ${platform.length} platform routes -> src/lib/redirects.ts`);
console.log(`  ${inv.posts.length} posts -> /blog/`);
console.log(`  ${links.length} BetterLinks`);
console.log(`  ${inv.categories.filter((c) => c.count === 0).length} empty categories`);
if (conflicts.length) { console.log('\nERROR: redirecting a path this build serves:'); conflicts.forEach((c) => console.log('  ' + c.from)); process.exitCode = 1; }
if (dupes.length) { console.log('\nERROR: duplicate `from`:'); [...new Set(dupes)].forEach((d) => console.log('  ' + d)); process.exitCode = 1; }
if (unbuilt.length) {
  console.log('\nWARNING: published in WordPress, not served by this build and not redirected:');
  unbuilt.forEach((u) => console.log('  ' + u));
  process.exitCode = 1;
}
