// Pulls /changelog/ into src/data/changelog.ts.
//
// From the LIVE page, not reference/html/changelog.html: the capture is already
// a release behind, and a stale entry list would put the page thousands of
// pixels out with nothing in the layout to blame.
//
// Run again when a release ships, until the changelog moves into the CMS.
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';

const b = await chromium.launch();
const p = await (await b.newContext()).newPage();
await p.goto('https://storefaq.io/changelog/', { waitUntil: 'networkidle', timeout: 60000 });
await p.evaluate(async () => { await document.fonts.ready; });

const entries = await p.evaluate(() => {
  /* Keep only the inline tags the copy actually uses, and drop every
   * attribute with them — §B1: no WordPress class may reach the output. */
  const KEEP = new Set(['STRONG', 'EM', 'B', 'I', 'CODE', 'A', 'BR']);
  const clean = (node) => [...node.childNodes].map((n) => {
    if (n.nodeType === 3) return n.textContent;
    if (n.nodeType !== 1) return '';
    const t = n.tagName;
    if (!KEEP.has(t)) return clean(n);
    if (t === 'BR') return '<br>';
    const tag = t.toLowerCase();
    const href = t === 'A' ? ` href="${n.getAttribute('href') ?? ''}"` : '';
    return `<${tag}${href}>${clean(n)}</${tag}>`;
  }).join('');
  const tidy = (s) => s.replace(/\s+/g, ' ').replace(/\s+([.,;:])/g, '$1').trim();

  return [...document.querySelectorAll('.timeline-row')].map((row) => {
    const date = row.querySelector('.eb-feature-list-title')?.textContent.trim() ?? '';
    const version = row.querySelector('.changelog-header')?.textContent.trim() ?? '';
    /* Walk the entry in document order: each h3 opens a section, each list
     * fills the one that is open. */
    const sections = [];
    for (const el of row.querySelectorAll('h3.wp-block-heading, ul.wp-block-list')) {
      if (el.tagName === 'H3') sections.push({ heading: tidy(el.textContent), items: [] });
      else if (sections.length) sections[sections.length - 1].items
        .push(...[...el.children].map((li) => tidy(clean(li))));
    }
    return { date, version, sections };
  });
});
await b.close();

const q = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const body = entries.map((e) => `  {
    date: ${q(e.date)},
    version: ${q(e.version)},
    sections: [
${e.sections.map((s) => `      {
        heading: ${q(s.heading)},
        items: [${s.items.length ? '\n' + s.items.map((i) => `          ${q(i)},`).join('\n') + '\n        ' : ''}],
      },`).join('\n')}
    ],
  },`).join('\n');

writeFileSync('src/data/changelog.ts', `/**
 * /changelog/ — the release timeline, newest first.
 *
 * Generated by scripts/scrape-changelog.mjs from the live page. Entry bodies
 * carry inline markup (<strong>, <em>, <a>, <code>, <br>) and nothing else:
 * every attribute and every wrapper the page builder added is dropped at
 * scrape time, so no WordPress class can reach the output (§B1).
 *
 * ${entries.length} entries, ${entries[0]?.version} (${entries[0]?.date}) down to ${entries.at(-1)?.version}.
 */
export interface ChangelogSection {
  heading: string;
  /** Inline HTML — rendered with set:html. */
  items: string[];
}

export interface ChangelogEntry {
  date: string;
  version: string;
  sections: ChangelogSection[];
}

export const changelog: ChangelogEntry[] = [
${body}
];
`);
